# ============================================================
# 알고리즘 자주 쓰는 문자열 함수 (import 불필요)
# ============================================================

s = "Hello, World!"

# ------------------------------------------------------------
# 탐색
# ------------------------------------------------------------

s.find("o")         # 4    | 첫 번째 위치, 없으면 -1
s.rfind("o")        # 8    | 오른쪽부터 탐색
s.index("o")        # 4    | find와 동일, 없으면 ValueError
s.count("l")        # 3    | 등장 횟수

"llo" in s          # True | 포함 여부


# ------------------------------------------------------------
# 변환
# ------------------------------------------------------------

s.upper()           # "HELLO, WORLD!"
s.lower()           # "hello, world!"
s.strip()           # 양쪽 공백 제거
s.lstrip()          # 왼쪽 공백 제거
s.rstrip()          # 오른쪽 공백 제거
s.strip("!")        # 특정 문자 제거 "Hello, World"

s.replace("l", "L")         # "HeLLo, WorLd!"
s.replace("l", "L", 2)      # "HeLLo, World!" | 최대 2번만 교체


# ------------------------------------------------------------
# 분리 / 결합
# ------------------------------------------------------------

"a,b,c".split(",")          # ['a','b','c']
"a b  c".split()            # ['a','b','c'] | 공백 기준, 연속 공백 처리
"a\nb\nc".splitlines()      # ['a','b','c'] | 줄바꿈 기준

",".join(["a","b","c"])     # "a,b,c"
" ".join(["hello","world"]) # "hello world"
"".join(["a","b","c"])      # "abc"

# 입력 한 줄에서 여러 정수 받기
a, b, c = map(int, input().split())


# ------------------------------------------------------------
# 검사
# ------------------------------------------------------------

"abc".isalpha()     # True  | 모두 알파벳
"123".isdigit()     # True  | 모두 숫자
"abc123".isalnum()  # True  | 알파벳 또는 숫자
"   ".isspace()     # True  | 모두 공백
"ABC".isupper()     # True  | 모두 대문자
"abc".islower()     # True  | 모두 소문자


# ------------------------------------------------------------
# 정렬 / 채우기
# ------------------------------------------------------------

"42".zfill(5)       # "00042" | 왼쪽 0으로 채우기
"hi".center(10)     # "    hi    "
"hi".ljust(10)      # "hi        " | 왼쪽 정렬
"hi".rjust(10)      # "        hi" | 오른쪽 정렬
"hi".center(10, "*") # "****hi****"


# ------------------------------------------------------------
# 슬라이싱
# ------------------------------------------------------------

s = "abcdef"
s[1:4]      # "bcd"
s[::-1]     # "fedcba" | 문자열 뒤집기
s[::2]      # "ace"    | 2칸씩
s[-3:]      # "def"    | 뒤에서 3개


# ------------------------------------------------------------
# 주의사항
# ------------------------------------------------------------

# 문자열은 불변(immutable) → 수정 불가, 리스트로 변환 후 작업
s = "hello"
# s[0] = 'H'  # TypeError

arr = list(s)   # ['h','e','l','l','o']
arr[0] = 'H'
result = "".join(arr)  # "Hello"

# 문자열 반복 연결은 느림 → join 사용
# 느림
result = ""
for c in "abc":
    result += c     # 매번 새 문자열 생성 O(n^2)

# 빠름
result = "".join(["a", "b", "c"])   # O(n)
