# ------------------------------------------------------------
# 수 관련
# ------------------------------------------------------------

round(3.5)          # 4   | 반올림 (단, .5는 짝수 방향 - 은행가 반올림)
round(3.14159, 2)   # 3.14 | 소수점 자리 지정

abs(-5)             # 5   | 절댓값

max(1, 2, 3)        # 3   | 최댓값
min(1, 2, 3)        # 1   | 최솟값
max([1, 2, 3])      # 3   | 리스트도 가능

sum([1, 2, 3, 4])   # 10  | 합계
sum(range(1, 101))  # 5050

pow(2, 10)          # 1024 | 거듭제곱 (2**10 과 동일)
pow(2, 10, 1000)    # 24   | pow(base, exp, mod) : 모듈러 거듭제곱 (대용량에서 유용)

divmod(17, 5)       # (3, 2) | 몫과 나머지 동시에


# ------------------------------------------------------------
# 리스트/순서 관련
# ------------------------------------------------------------

sorted([3, 1, 2])               # [1, 2, 3]  | 새 리스트 반환
sorted([3, 1, 2], reverse=True) # [3, 2, 1]

# key 함수로 정렬 기준 지정
words = ["banana", "apple", "kiwi"]
sorted(words, key=len)          # ['kiwi', 'apple', 'banana'] | 길이 순

# 튜플 리스트 정렬 (두 번째 원소 기준)
pairs = [(1, 3), (2, 1), (3, 2)]
sorted(pairs, key=lambda x: x[1])  # [(2,1), (3,2), (1,3)]

# 리스트 자체를 정렬 (반환값 없음)
arr = [3, 1, 2]
arr.sort()                      # arr = [1, 2, 3]
arr.sort(reverse=True)          # arr = [3, 2, 1]

reversed([1, 2, 3])             # 이터레이터 반환
list(reversed([1, 2, 3]))       # [3, 2, 1]

enumerate([10, 20, 30])         # (0,10), (1,20), (2,30) | 인덱스+값 동시에
for i, v in enumerate([10, 20, 30]):
    pass  # i=0,v=10 / i=1,v=20 / i=2,v=30

zip([1, 2, 3], [4, 5, 6])       # (1,4), (2,5), (3,6) | 여러 리스트 묶기
for a, b in zip([1,2,3], [4,5,6]):
    pass  # a=1,b=4 / a=2,b=5 / a=3,b=6


# ------------------------------------------------------------
# 변환 관련
# ------------------------------------------------------------

int("42")           # 42   | 문자열 → 정수
int("1010", 2)      # 10   | 2진수 문자열 → 10진수 정수
int("ff", 16)       # 255  | 16진수 문자열 → 10진수 정수

str(42)             # "42" | 정수 → 문자열
float("3.14")       # 3.14

list("abc")         # ['a', 'b', 'c'] | 문자열 → 리스트
list(range(5))      # [0, 1, 2, 3, 4]

bin(10)             # '0b1010' | 10진수 → 2진수 문자열
oct(8)              # '0o10'   | 10진수 → 8진수 문자열
hex(255)            # '0xff'   | 10진수 → 16진수 문자열

ord('A')            # 65   | 문자 → ASCII 코드
chr(65)             # 'A'  | ASCII 코드 → 문자


# ------------------------------------------------------------
# 조건/탐색 관련
# ------------------------------------------------------------

any([False, False, True])   # True  | 하나라도 True면 True
all([True, True, True])     # True  | 모두 True여야 True
any([False, False, False])  # False
all([True, False, True])    # False

# 활용: 리스트 내 조건 검사
nums = [2, 4, 6, 8]
any(x % 2 != 0 for x in nums)  # False | 홀수가 하나라도 있는가
all(x % 2 == 0 for x in nums)  # True  | 모두 짝수인가

map(int, ["1", "2", "3"])       # 이터레이터 반환
list(map(int, ["1", "2", "3"])) # [1, 2, 3] | 한 줄 입력 변환에 자주 사용
a, b, c = map(int, input().split())  # 공백 구분 입력

filter(lambda x: x > 2, [1, 2, 3, 4])       # 이터레이터
list(filter(lambda x: x > 2, [1, 2, 3, 4])) # [3, 4]
