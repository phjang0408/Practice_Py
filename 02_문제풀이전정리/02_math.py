# ============================================================
# 알고리즘 자주 쓰는 math 모듈
# ============================================================
import math

# ------------------------------------------------------------
# 올림 / 내림 / 반올림
# ------------------------------------------------------------

math.floor(3.9)     # 3    | 내림 (음수 주의: floor(-3.1) = -4)
math.ceil(3.1)      # 4    | 올림
round(3.5)          # 4    | 반올림 (내장 함수, .5는 은행가 방식)
math.floor(3.5 + 0.5)  # 4 | 항상 .5 올림이 필요할 때


# ------------------------------------------------------------
# 제곱 / 로그
# ------------------------------------------------------------

math.sqrt(16)       # 4.0  | 제곱근
math.isqrt(16)      # 4    | 정수 제곱근 (소수점 없음, 파이썬 3.8+)
math.isqrt(17)      # 4    | floor(sqrt(17))

math.log(8, 2)      # 3.0  | log₂(8)
math.log10(1000)    # 3.0  | log₁₀(1000)
math.log(math.e)    # 1.0  | 자연로그


# ------------------------------------------------------------
# 최대공약수 / 최소공배수
# ------------------------------------------------------------

math.gcd(12, 8)     # 4    | 최대공약수 (GCD)
math.gcd(12, 8, 6)  # 2    | 여러 수 한번에 (파이썬 3.9+)

# 최소공배수 (LCM) - 파이썬 3.9+
math.lcm(4, 6)      # 12
math.lcm(4, 6, 10)  # 60

# 파이썬 3.8 이하에서 LCM 직접 구현
def lcm(a, b):
    return a * b // math.gcd(a, b)


# ------------------------------------------------------------
# 팩토리얼 / 순열 / 조합
# ------------------------------------------------------------

math.factorial(5)           # 120  | 5!

math.perm(5, 2)             # 20   | 5P2 = 5*4 (파이썬 3.8+)
math.comb(5, 2)             # 10   | 5C2 = 10  (파이썬 3.8+)

# 직접 구현 (하위 버전 대비)
def perm(n, r):
    return math.factorial(n) // math.factorial(n - r)

def comb(n, r):
    return math.factorial(n) // (math.factorial(r) * math.factorial(n - r))


# ------------------------------------------------------------
# 무한대 / 상수
# ------------------------------------------------------------

math.inf         # 양의 무한대 (최솟값 초기화에 자주 사용)
-math.inf        # 음의 무한대 (최댓값 초기화에 자주 사용)
math.pi          # 3.14159...
math.e           # 2.71828...

# 활용: 최솟값 탐색 초기화
min_val = math.inf
for x in [5, 3, 8, 1]:
    if x < min_val:
        min_val = x
# min_val = 1


# ------------------------------------------------------------
# 주의사항
# ------------------------------------------------------------

# 부동소수점 비교는 직접 == 사용 금지
math.sqrt(2) ** 2 == 2      # False (부동소수점 오차)
abs(math.sqrt(2)**2 - 2) < 1e-9  # True (오차 허용 비교)

math.isclose(math.sqrt(2)**2, 2)  # True (권장 방식)
